-- =========================================================
-- BONHAGAN TRANSIT — PostgreSQL Database Schema
-- Optimized for Neon PostgreSQL & PHP PDO Backend
-- =========================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =========================================================
-- 1. USER PROFILES / ACCOUNTS
-- Supports native PHP password_hash() and session-based authentication.
-- =========================================================

CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    mobile_number VARCHAR(30),
    role VARCHAR(20) NOT NULL DEFAULT 'passenger'
        CHECK (role IN ('passenger', 'staff', 'admin')),
    account_status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (account_status IN ('active', 'suspended', 'deactivated')),
    profile_image_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 2. BUS TYPES AND VEHICLES
-- =========================================================

CREATE TABLE IF NOT EXISTS public.bus_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR(50) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.buses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_type_id BIGINT NOT NULL REFERENCES public.bus_types(id),
    bus_number VARCHAR(50) NOT NULL UNIQUE,
    plate_number VARCHAR(30) NOT NULL UNIQUE,
    bus_name VARCHAR(100),
    seating_capacity INTEGER NOT NULL CHECK (seating_capacity >= 0),
    standing_capacity INTEGER NOT NULL DEFAULT 0
        CHECK (standing_capacity >= 0),
    status VARCHAR(30) NOT NULL DEFAULT 'active'
        CHECK (status IN (
            'active', 'maintenance', 'inactive', 'retired'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.bus_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id BIGINT NOT NULL REFERENCES public.buses(id) ON DELETE CASCADE,
    seat_number VARCHAR(20) NOT NULL,
    seat_row INTEGER,
    seat_column INTEGER,
    seat_type VARCHAR(30) DEFAULT 'regular',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (bus_id, seat_number)
);

-- =========================================================
-- 3. ROUTES AND STOPS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code VARCHAR(30) NOT NULL UNIQUE,
    route_name VARCHAR(150) NOT NULL,
    direction VARCHAR(20) NOT NULL
        CHECK (direction IN ('northbound', 'southbound')),
    origin_name VARCHAR(150) NOT NULL,
    destination_name VARCHAR(150) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_name VARCHAR(150) NOT NULL,
    address TEXT,
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Defines ordered stops belonging to a route
CREATE TABLE IF NOT EXISTS public.route_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL REFERENCES public.routes(id) ON DELETE CASCADE,
    stop_id BIGINT NOT NULL REFERENCES public.stops(id),
    sequence_number INTEGER NOT NULL CHECK (sequence_number > 0),
    distance_from_origin NUMERIC(10, 2),
    estimated_minutes_from_origin INTEGER,
    UNIQUE (route_id, sequence_number),
    UNIQUE (route_id, stop_id)
);

-- =========================================================
-- 4. TRIPS / BUS SCHEDULES
-- =========================================================

CREATE TABLE IF NOT EXISTS public.trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_code VARCHAR(50) NOT NULL UNIQUE,
    route_id BIGINT NOT NULL REFERENCES public.routes(id),
    bus_id BIGINT NOT NULL REFERENCES public.buses(id),
    departure_datetime TIMESTAMPTZ NOT NULL,
    estimated_arrival TIMESTAMPTZ NOT NULL,
    actual_departure TIMESTAMPTZ,
    actual_arrival TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL DEFAULT 'scheduled'
        CHECK (status IN (
            'scheduled',
            'boarding',
            'departed',
            'delayed',
            'completed',
            'cancelled'
        )),
    standing_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    standing_capacity_override INTEGER
        CHECK (
            standing_capacity_override IS NULL
            OR standing_capacity_override >= 0
        ),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (estimated_arrival > departure_datetime)
);

CREATE TABLE IF NOT EXISTS public.trip_staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES public.trips(id) ON DELETE CASCADE,
    staff_id UUID NOT NULL REFERENCES public.profiles(id),
    assignment_role VARCHAR(30) NOT NULL
        CHECK (assignment_role IN (
            'driver', 'conductor', 'inspector'
        )),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (trip_id, staff_id, assignment_role)
);

-- =========================================================
-- 5. BOOKINGS AND PASSENGERS
-- One booking can contain multiple passengers.
-- =========================================================

CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR(40) NOT NULL UNIQUE,
    user_id UUID NOT NULL REFERENCES public.profiles(id),
    trip_id BIGINT NOT NULL REFERENCES public.trips(id),
    booking_status VARCHAR(30) NOT NULL DEFAULT 'pending'
        CHECK (booking_status IN (
            'pending',
            'confirmed',
            'cancelled',
            'expired',
            'completed'
        )),
    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (total_amount >= 0),
    payment_deadline TIMESTAMPTZ,
    booking_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.booking_passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES public.bookings(id)
        ON DELETE CASCADE,
    passenger_name VARCHAR(150) NOT NULL,
    passenger_type VARCHAR(30) NOT NULL DEFAULT 'regular'
        CHECK (passenger_type IN (
            'regular', 'student', 'senior_citizen'
        )),
    mobile_number VARCHAR(30),
    boarding_route_stop_id BIGINT NOT NULL
        REFERENCES public.route_stops(id),
    dropoff_route_stop_id BIGINT NOT NULL
        REFERENCES public.route_stops(id),
    base_fare NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (base_fare >= 0),
    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (discount_amount >= 0),
    final_fare NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (final_fare >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 6. SEAT AND STANDING ALLOCATIONS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.passenger_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id BIGINT NOT NULL UNIQUE
        REFERENCES public.booking_passengers(id) ON DELETE CASCADE,
    trip_id BIGINT NOT NULL REFERENCES public.trips(id),
    allocation_type VARCHAR(20) NOT NULL
        CHECK (allocation_type IN ('seat', 'standing')),
    seat_id BIGINT REFERENCES public.bus_seats(id),
    allocation_status VARCHAR(20) NOT NULL DEFAULT 'held'
        CHECK (allocation_status IN (
            'held', 'confirmed', 'released', 'expired'
        )),
    hold_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (
        (allocation_type = 'seat' AND seat_id IS NOT NULL)
        OR
        (allocation_type = 'standing' AND seat_id IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_allocations_trip
ON public.passenger_allocations(trip_id);

CREATE INDEX IF NOT EXISTS idx_allocations_seat
ON public.passenger_allocations(seat_id);

-- =========================================================
-- 7. FARE MANAGEMENT
-- =========================================================

CREATE TABLE IF NOT EXISTS public.fare_matrices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL REFERENCES public.routes(id),
    bus_type_id BIGINT NOT NULL REFERENCES public.bus_types(id),
    effective_from DATE NOT NULL,
    effective_until DATE,
    base_rate NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (base_rate >= 0),
    per_km_rate NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (per_km_rate >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (
        effective_until IS NULL
        OR effective_until >= effective_from
    )
);

CREATE TABLE IF NOT EXISTS public.fare_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fare_matrix_id BIGINT NOT NULL
        REFERENCES public.fare_matrices(id) ON DELETE CASCADE,
    origin_route_stop_id BIGINT NOT NULL
        REFERENCES public.route_stops(id),
    destination_route_stop_id BIGINT NOT NULL
        REFERENCES public.route_stops(id),
    fare_amount NUMERIC(12, 2) NOT NULL
        CHECK (fare_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (
        fare_matrix_id,
        origin_route_stop_id,
        destination_route_stop_id
    )
);

-- =========================================================
-- 8. DISCOUNT TYPES AND VERIFICATION
-- =========================================================

CREATE TABLE IF NOT EXISTS public.discount_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discount_name VARCHAR(80) NOT NULL UNIQUE,
    discount_percentage NUMERIC(5, 2) NOT NULL
        CHECK (
            discount_percentage >= 0
            AND discount_percentage <= 100
        ),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.discount_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id BIGINT NOT NULL
        REFERENCES public.booking_passengers(id) ON DELETE CASCADE,
    discount_type_id BIGINT NOT NULL
        REFERENCES public.discount_types(id),
    document_path TEXT NOT NULL,
    verification_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (verification_status IN (
            'pending', 'approved', 'rejected'
        )),
    reviewed_by UUID REFERENCES public.profiles(id),
    reviewed_at TIMESTAMPTZ,
    review_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 9. PAYMENTS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES public.bookings(id),
    payment_reference VARCHAR(100) UNIQUE,
    payment_method VARCHAR(30) NOT NULL
        CHECK (payment_method IN (
            'online', 'terminal'
        )),
    payment_provider VARCHAR(80),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (payment_status IN (
            'pending',
            'processing',
            'paid',
            'failed',
            'expired',
            'refunded',
            'cancelled'
        )),
    paid_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.payment_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES public.payments(id)
        ON DELETE CASCADE,
    event_type VARCHAR(80) NOT NULL,
    event_details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 10. ELECTRONIC TICKETS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id BIGINT NOT NULL UNIQUE
        REFERENCES public.booking_passengers(id),
    ticket_reference VARCHAR(50) NOT NULL UNIQUE,
    qr_token UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    ticket_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (ticket_status IN (
            'pending', 'valid', 'boarded',
            'cancelled', 'expired', 'refunded'
        )),
    issued_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.boarding_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES public.tickets(id),
    verified_by UUID REFERENCES public.profiles(id),
    boarded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    verification_method VARCHAR(20) NOT NULL DEFAULT 'qr'
        CHECK (verification_method IN ('qr', 'manual')),
    notes TEXT
);

-- =========================================================
-- 11. NOTIFICATIONS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id)
        ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    message TEXT NOT NULL,
    notification_type VARCHAR(40) DEFAULT 'general',
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 12. TRIP STATUS HISTORY
-- =========================================================

CREATE TABLE IF NOT EXISTS public.trip_status_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES public.trips(id)
        ON DELETE CASCADE,
    previous_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    updated_by UUID REFERENCES public.profiles(id),
    remarks TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 13. INCIDENT REPORTS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES public.trips(id),
    reported_by UUID NOT NULL REFERENCES public.profiles(id),
    incident_type VARCHAR(80) NOT NULL,
    description TEXT NOT NULL,
    incident_status VARCHAR(30) NOT NULL DEFAULT 'reported'
        CHECK (incident_status IN (
            'reported', 'investigating', 'resolved', 'closed'
        )),
    resolution_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- 14. AUDIT LOGS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.profiles(id),
    action VARCHAR(120) NOT NULL,
    affected_table VARCHAR(100),
    record_id VARCHAR(100),
    details JSONB,
    ip_address INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
